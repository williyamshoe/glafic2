#!/usr/bin/env python
"""Convert example_data/glafic_rj2129_v1_* into glafic input files.

Writes (in this directory):
  rxj2129.input        glafic input file (lens model, cosmology flags, setopt)
  rxj2129_obs.dat      multiple images in glafic readobs_point format
  rxj2129_galfile.dat  cluster members (x, y, L/L*, e, PA) for the 'gals' model
  rxj2129_prior.dat    parameter ranges (parprior format)

Coordinates are arcsec relative to the BCG with glafic's convention
x = (RA0 - RA) cos(Dec0) * 3600 (positive to the west), y = (Dec - Dec0) * 3600.
"""
import os
from collections import OrderedDict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "..", "example_data")
ZL = 0.234


def radec_to_xy(ra, dec, ra0, dec0):
    return (ra0 - ra) * 3600.0 * np.cos(np.deg2rad(dec0)), (dec - dec0) * 3600.0


def load():
    gal = np.loadtxt(os.path.join(DATA, "glafic_rj2129_v1_memgal.txt"))
    ra0, dec0 = gal[0, 0], gal[0, 1]          # BCG (L = L*)
    gx, gy = radec_to_xy(gal[:, 0], gal[:, 1], ra0, dec0)
    gals = np.column_stack([gx, gy, gal[:, 2], gal[:, 3], gal[:, 4]])
    img = np.loadtxt(os.path.join(DATA, "glafic_rj2129_v1_mulimage.txt"))
    ix, iy = radec_to_xy(img[:, 1], img[:, 2], ra0, dec0)
    systems = OrderedDict()
    for row, x, y in zip(img, ix, iy):
        sid = int(np.floor(row[0] + 1e-6))
        systems.setdefault(sid, dict(zs=row[4], zerr=row[5], err=row[3], xy=[]))["xy"].append((x, y))
    return (ra0, dec0), gals, systems


def write_all(outdir=HERE, bcg=False, mpoles=(), eta_free=True, pos_err=None):
    """Write the glafic files.  Defaults follow the glafic recipe of Oguri et
    al. (VENUS, 2026, Sec. 2.3): elliptical NFW halo (all 6 parameters free,
    1 < c < 40, e < 0.8), pseudo-Jaffe members with sigma ~ L^1/4 and
    r_trun ~ L^eta (100 < sigma* < 400 km/s, 1" < r_trun* < 100",
    0.2 < eta < 1.5), external shear, and optional n = 2 multipoles.
    pos_err: override the catalogue positional error [arcsec] (the paper
    rescales errors so that the best fit has reduced chi^2 ~ 1).

    bcg    : model the BCG separately (pseudo-Jaffe 'jaffe', e and PA from the
             catalogue, sigma and truncation radius free) and remove it from
             the 'gals' member catalogue.
    mpoles : sequence of (m, n) multipole perturbations ('mpole') centred on
             the BCG, with amplitude and angle free.
    """
    (ra0, dec0), gals, systems = load()
    bcg_row = gals[0]
    if bcg:
        gals = gals[1:]
    np.savetxt(os.path.join(outdir, "rxj2129_galfile.dat"), gals, fmt="%12.6f %12.6f %10.5f %7.3f %8.2f",
               header="x[arcsec] y[arcsec] L/L* e PA[deg]  (BCG at RA=%.7f Dec=%.7f)" % (ra0, dec0))
    with open(os.path.join(outdir, "rxj2129_obs.dat"), "w") as f:
        f.write("# id nimg zs zs_err ; then x y flux pos_err flux_err td td_err parity\n")
        for k, (sid, s) in enumerate(systems.items(), start=1):
            f.write(f"{k} {len(s['xy'])} {s['zs']:.4f} {s['zerr']:.4f}   # system {sid}\n")
            for x, y in s["xy"]:
                f.write(f"{x:10.5f} {y:10.5f} 0.0 {pos_err or s['err']:.3f} 0.0 0.0 0.0 0\n")
    # initial guesses: images' centroid for the sources
    lines = ["# glafic input for RXJ2129 (generated by build_rxj2129.py)",
             "omega     0.300000", "lambda    0.700000", "weos     -1.000000", "hubble    0.700000",
             "prefix    rxj2129",
             "xmin     -60.0", "ymin     -60.0", "xmax      60.0", "ymax      60.0",
             "pix_ext   0.2", "pix_poi   1.0", "maxlev    6",
             "galfile   rxj2129_galfile.dat",
             "chi2_splane    1", "chi2_checknimg 0",
             "flatfix   1", "ovary     1", "wvary     1", "wavary    1", "hvary     0",
             "", f"startup {3 + int(bcg) + len(mpoles)} 0 {len(systems)}",
             f"lens anfw  {ZL} 8.0e14  0.0  0.0  0.4  -20.0  6.0  0.0",
             f"lens gals  {ZL} 200.0   0.0  0.0  0.0    0.0 20.0  1.0",
             f"lens pert  {ZL} 2.0     0.0  0.0  0.05  30.0  0.0  0.0"]
    if bcg:
        lines.append(f"lens jaffe {ZL} 300.0   0.0  0.0  {bcg_row[3]:.3f} {bcg_row[4]:.1f}  10.0  0.01")
    for (mm, nn) in mpoles:
        lines.append(f"lens mpole {ZL} 2.0     0.0  0.0  0.01  0.0  {mm:.1f}  {nn:.1f}")  # (m, n)
    for s in systems.values():
        c = np.mean(s["xy"], axis=0)
        lines.append(f"point {s['zs']:.4f} {c[0]:.4f} {c[1]:.4f}")
    lines += ["end_startup", "", "start_setopt",
              "0 1 1 1 1 1 1 0",      # anfw: M, x, y, e, PA, c
              "0 1 0 0 0 0 1 %d" % int(eta_free),   # gals: sigma*, r_trunc*, eta
              "0 0 0 0 1 1 0 0"]      # pert: gamma, theta
    if bcg:
        lines.append("0 1 0 0 0 0 1 0")       # BCG: sigma, truncation radius
    for _ in mpoles:
        lines.append("0 0 0 0 1 1 0 0")       # multipole: amplitude, angle
    for s in systems.values():
        lines.append(f"{1 if s['zerr'] > 0 else 0} 1 1")
    lines += ["end_setopt", "", "start_command",
              "readobs_point rxj2129_obs.dat", "parprior rxj2129_prior.dat", "optimize", "quit", ""]
    open(os.path.join(outdir, "rxj2129.input"), "w").write("\n".join(lines))
    # Angles get a wide range here (no hard wall); the sampler restricts them to
    # one period around the best fit (period 180 deg for ellipses/shear,
    # 360/m for multipoles) to avoid the exact angle degeneracy.
    nl = 3 + int(bcg)
    prior = ["# parameter ranges (flat priors inside); Oguri et al. VENUS recipe",
             "range lens 1 2 1.0e13 1.0e16", "range lens 1 3 -15.0 15.0", "range lens 1 4 -15.0 15.0",
             "range lens 1 5 0.0 0.8", "range lens 1 6 -720.0 720.0", "range lens 1 7 1.0 40.0",
             "range lens 2 2 100.0 400.0", "range lens 2 7 1.0 100.0", "range lens 2 8 0.2 1.5",
             "range lens 3 5 0.0 0.5", "range lens 3 6 -720.0 720.0",
             *(["range lens 4 2 50.0 800.0", "range lens 4 7 0.1 300.0"] if bcg else []),
             *sum(([f"range lens {nl + 1 + q} 5 0.0 0.5", f"range lens {nl + 1 + q} 6 -720.0 720.0"]
                   for q in range(len(mpoles))), []),
             "range omega 0.05 1.0", "range weos -2.5 0.0", "range wa -10.0 10.0"]
    for k, s in enumerate(systems.values(), start=1):
        if s["zerr"] > 0:
            prior.append(f"range point {k} 1 {max(s['zs'] - 4 * s['zerr'], ZL + 0.05):.3f} {s['zs'] + 4 * s['zerr']:.3f}")
    open(os.path.join(outdir, "rxj2129_prior.dat"), "w").write("\n".join(prior) + "\n")
    return systems


if __name__ == "__main__":
    s = write_all()
    print(f"{len(s)} systems, {sum(len(v['xy']) for v in s.values())} images written to {HERE}")
